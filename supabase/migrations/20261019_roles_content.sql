-- PalEdu role-based curriculum platform.
-- Apply to an OWNED Supabase project; never paste service role keys into source.
-- The initial administrator must be provisioned privately by a project operator.

create extension if not exists pgcrypto;

create table if not exists public.paledu_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  username text unique,
  role text not null default 'student'
    check (role in ('student','teacher','trainer','admin')),
  grade smallint check (grade between 1 and 12),
  branch text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.paledu_current_role()
returns text language sql stable security definer
set search_path = '' as $$
  select coalesce((select role from public.paledu_profiles
                   where user_id = auth.uid()), 'guest')
$$;

revoke all on function public.paledu_current_role() from public;
grant execute on function public.paledu_current_role() to authenticated;

create or replace function public.paledu_new_user()
returns trigger language plpgsql security definer
set search_path = '' as $$
begin
  insert into public.paledu_profiles (user_id, display_name, role)
  values (new.id,
          left(coalesce(new.raw_user_meta_data ->> 'display_name',''),100),
          'student')
  on conflict (user_id) do nothing;
  return new;
end;
$$;
drop trigger if exists paledu_auth_user_insert on auth.users;
create trigger paledu_auth_user_insert
after insert on auth.users for each row execute function public.paledu_new_user();

create table if not exists public.paledu_role_requests (
  request_id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  requested_role text not null check(requested_role in ('teacher','trainer')),
  statement text not null check (length(statement) between 10 and 1000),
  status text not null default 'pending'
    check(status in ('pending','approved','rejected')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id)
);
create unique index if not exists paledu_role_request_open
  on public.paledu_role_requests (user_id) where status='pending';

create table if not exists public.paledu_resources (
  resource_id uuid primary key default gen_random_uuid(),
  created_by uuid not null references auth.users(id),
  title text not null check(length(title) between 4 and 180),
  description text not null default '',
  kind text not null check(kind in ('book','handout','video','lesson')),
  grade smallint not null check(grade between 1 and 12),
  branch text not null default 'عام',
  subject text not null check(length(subject) between 2 and 100),
  semester smallint check(semester in (1,2)),
  asset_path text,
  external_url text check(external_url is null or external_url ~ '^https://'),
  rights_note text not null default '',
  license_verified boolean not null default false,
  status text not null default 'draft'
    check(status in ('draft','pending','published','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  reviewed_by uuid references auth.users(id),
  published_at timestamptz,
  constraint paledu_resource_source
    check ((asset_path is not null) or (external_url is not null)),
  constraint paledu_asset_owner
    check (asset_path is null or asset_path like created_by::text || '/%'),
  constraint paledu_publish_requires_rights
    check(status <> 'published' or
      (license_verified and length(trim(rights_note)) >= 10))
);
create index if not exists paledu_public_catalog
  on public.paledu_resources(grade,branch,subject,kind,published_at desc)
  where status='published';
create index if not exists paledu_author_drafts
  on public.paledu_resources(created_by,status,created_at desc);

create table if not exists public.paledu_audit (
  event_id bigint generated by default as identity primary key,
  actor uuid references auth.users(id),
  action text not null,
  entity_id uuid,
  happened_at timestamptz not null default now()
);

alter table public.paledu_profiles enable row level security;
alter table public.paledu_role_requests enable row level security;
alter table public.paledu_resources enable row level security;
alter table public.paledu_audit enable row level security;

drop policy if exists paledu_profiles_read on public.paledu_profiles;
create policy paledu_profiles_read on public.paledu_profiles
  for select to authenticated
  using (user_id=auth.uid() or public.paledu_current_role()='admin');
drop policy if exists paledu_profiles_update on public.paledu_profiles;
create policy paledu_profiles_update on public.paledu_profiles
  for update to authenticated using (user_id=auth.uid())
  with check(user_id=auth.uid());

drop policy if exists paledu_role_requests_read on public.paledu_role_requests;
create policy paledu_role_requests_read on public.paledu_role_requests
  for select to authenticated
  using(user_id=auth.uid() or public.paledu_current_role()='admin');
drop policy if exists paledu_role_requests_insert on public.paledu_role_requests;
create policy paledu_role_requests_insert on public.paledu_role_requests
  for insert to authenticated
  with check(user_id=auth.uid() and status='pending' and
    public.paledu_current_role()='student');

drop policy if exists paledu_resources_read on public.paledu_resources;
create policy paledu_resources_read on public.paledu_resources
  for select to authenticated using(
    status='published' or created_by=auth.uid()
    or public.paledu_current_role()='admin');
drop policy if exists paledu_resources_insert on public.paledu_resources;
create policy paledu_resources_insert on public.paledu_resources
  for insert to authenticated with check (
    created_by=auth.uid() and status in ('draft','pending') and
    public.paledu_current_role() in ('teacher','trainer','admin'));
drop policy if exists paledu_resources_update on public.paledu_resources;
create policy paledu_resources_update on public.paledu_resources
  for update to authenticated using (
    created_by=auth.uid() and status in ('draft','rejected') and
    public.paledu_current_role() in ('teacher','trainer','admin'))
  with check(created_by=auth.uid() and status in ('draft','pending') and
    license_verified=false);
drop policy if exists paledu_resources_delete on public.paledu_resources;
create policy paledu_resources_delete on public.paledu_resources
  for delete to authenticated using (
    created_by=auth.uid() and status in ('draft','rejected') and
    public.paledu_current_role() in ('teacher','trainer','admin'));

