-- Admin changes go through privilege-checked SECURITY DEFINER routines.
create or replace function public.paledu_review_educator(
  request_uid uuid, accepted boolean
) returns void language plpgsql security definer set search_path = '' as $$
declare r public.paledu_role_requests%rowtype;
begin
  if auth.uid() is null or public.paledu_current_role()<>'admin' then
    raise exception 'Not authorized';
  end if;
  select * into r from public.paledu_role_requests
    where request_id=request_uid and status='pending' for update;
  if not found then raise exception 'Request not available'; end if;
  update public.paledu_role_requests set
    status=case when accepted then 'approved' else 'rejected' end,
    reviewed_by=auth.uid(), reviewed_at=now()
    where request_id=request_uid;
  if accepted then
    update public.paledu_profiles set role=r.requested_role,
      updated_at=now() where user_id=r.user_id and role='student';
  end if;
  insert into public.paledu_audit(actor,action,entity_id)
    values (auth.uid(),case when accepted then 'approve_role' else 'reject_role' end,
            request_uid);
end;
$$;
revoke all on function public.paledu_review_educator(uuid,boolean) from public;
grant execute on function public.paledu_review_educator(uuid,boolean)
  to authenticated;

create or replace function public.paledu_review_resource(
  resource_uid uuid, accepted boolean
) returns void language plpgsql security definer set search_path = '' as $$
declare r public.paledu_resources%rowtype;
begin
  if auth.uid() is null or public.paledu_current_role()<>'admin' then
    raise exception 'Not authorized';
  end if;
  select * into r from public.paledu_resources
    where resource_id=resource_uid and status='pending' for update;
  if not found then raise exception 'Not available'; end if;
  if accepted and length(trim(r.rights_note))<10 then
    raise exception 'Rights evidence is required before publishing';
  end if;
  update public.paledu_resources
    set status=case when accepted then 'published' else 'rejected' end,
        license_verified=accepted,
        reviewed_by=auth.uid(),updated_at=now(),
        published_at=case when accepted then now() else null end
    where resource_id=resource_uid;
  insert into public.paledu_audit(actor,action,entity_id)
    values(auth.uid(),case when accepted then 'publish' else 'reject_resource' end,
           resource_uid);
end;
$$;
revoke all on function public.paledu_review_resource(uuid,boolean) from public;
grant execute on function public.paledu_review_resource(uuid,boolean)
  to authenticated;

-- Private storage; teachers write ONLY into own UUID prefix.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('paledu-curriculum','paledu-curriculum',false,52428800,
  array['application/pdf','image/png','image/jpeg','video/mp4'])
on conflict (id) do nothing;

drop policy if exists paledu_asset_insert on storage.objects;
create policy paledu_asset_insert on storage.objects for insert to authenticated
  with check(
    bucket_id='paledu-curriculum' and
    split_part(name,'/',1)=auth.uid()::text and
    public.paledu_current_role() in ('teacher','trainer','admin'));
drop policy if exists paledu_asset_read on storage.objects;
create policy paledu_asset_read on storage.objects for select to authenticated
  using(bucket_id='paledu-curriculum' and (
    (split_part(name,'/',1)=auth.uid()::text and
      public.paledu_current_role() in ('teacher','trainer','admin'))
    or public.paledu_current_role()='admin'
    or exists (select 1 from public.paledu_resources r
      where r.asset_path=name and r.status='published')
  ));
-- No update/delete policies; uploaded objects are immutable and retained for audit.
